import type { SpeechClipEnd, TurnRef } from '@proj-airi/core-agent'

import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { PlaybackCaption } from './playback-caption'

const turn: TurnRef = { sessionId: 'session', turnId: 'turn' }
const nextTurn: TurnRef = { sessionId: 'session', turnId: 'next-turn' }
const first = { id: 'first', text: 'A new adventure.' }
const second = { id: 'second', text: 'Let us begin.' }

describe('playbackCaption', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())

  it('does not show generated text without actual playback', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    caption.updateActiveTurns([])
    vi.runAllTimers()

    expect(publish).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })

  it('waits for response closure when playback ends first', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    vi.advanceTimersByTime(10_000)
    expect(publish.mock.calls).toEqual([[first.text]])
    expect(vi.getTimerCount()).toBe(0)

    caption.updateActiveTurns([])
    vi.advanceTimersByTime(2999)
    expect(publish.mock.calls).toEqual([[first.text]])
    vi.advanceTimersByTime(1)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it.each<SpeechClipEnd['status']>(['ended', 'stopped', 'failed'])('waits for %s audio after the response closes', (status) => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(10_000)
    expect(publish.mock.calls).toEqual([[first.text]])
    expect(vi.getTimerCount()).toBe(0)

    output.onPlaybackEnd(first, { status })
    vi.advanceTimersByTime(2999)
    expect(publish.mock.calls).toEqual([[first.text]])
    vi.advanceTimersByTime(1)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('keeps the last segment through a long synthesis gap and replaces it at the next playback start', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    vi.advanceTimersByTime(60_000)
    expect(publish.mock.calls).toEqual([[first.text]])

    output.onPlaybackStart(second)
    expect(publish.mock.calls).toEqual([[first.text], [second.text]])
    caption.updateActiveTurns([])
    output.onPlaybackEnd(second, { status: 'ended' })
    vi.advanceTimersByTime(3000)
    expect(publish).toHaveBeenLastCalledWith('')
  })

  it('waits for every started clip when closure precedes their completion callbacks', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackStart(second)
    caption.updateActiveTurns([])
    output.onPlaybackEnd(first, { status: 'ended' })
    vi.advanceTimersByTime(5000)
    expect(publish).toHaveBeenLastCalledWith(second.text)
    expect(vi.getTimerCount()).toBe(0)

    output.onPlaybackEnd(second, { status: 'ended' })
    vi.advanceTimersByTime(3000)
    expect(publish).toHaveBeenLastCalledWith('')
  })

  it('cancels the previous hide timer when a newer turn actually starts audio', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const oldOutput = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    oldOutput.onPlaybackStart(first)
    oldOutput.onPlaybackEnd(first, { status: 'ended' })
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(2000)

    const nextOutput = caption.connectTurn(nextTurn)
    caption.updateActiveTurns([nextTurn])
    nextOutput.onPlaybackStart(second)
    vi.advanceTimersByTime(1000)
    expect(publish.mock.calls).toEqual([[first.text], [second.text]])
    nextOutput.onPlaybackEnd(second, { status: 'ended' })
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(2999)
    expect(publish).toHaveBeenLastCalledWith(second.text)
    vi.advanceTimersByTime(1)
    expect(publish).toHaveBeenLastCalledWith('')
  })

  it('does not prolong an old caption for a new response that has not played audio', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(2000)
    caption.connectTurn(nextTurn)
    caption.updateActiveTurns([nextTurn])
    vi.advanceTimersByTime(1000)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('does not let old completion callbacks hide a newer caption', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const oldOutput = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    oldOutput.onPlaybackStart(first)
    const nextOutput = caption.connectTurn(nextTurn)
    caption.updateActiveTurns([turn, nextTurn])
    nextOutput.onPlaybackStart(second)
    caption.updateActiveTurns([nextTurn])
    oldOutput.onPlaybackEnd(first, { status: 'stopped' })
    vi.advanceTimersByTime(3000)
    expect(publish.mock.calls).toEqual([[first.text], [second.text]])
    expect(vi.getTimerCount()).toBe(0)
  })

  it('shows actual resumed audio from an earlier response without accepting unrelated completion callbacks', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const oldOutput = caption.connectTurn(turn)
    const nextOutput = caption.connectTurn(nextTurn)
    caption.updateActiveTurns([turn, nextTurn])
    nextOutput.onPlaybackStart(second)
    oldOutput.onPlaybackStart(first)
    expect(publish.mock.calls).toEqual([[second.text], [first.text]])
    oldOutput.onPlaybackEnd(first, { status: 'ended' })
    nextOutput.onPlaybackEnd(second, { status: 'ended' })
    caption.updateActiveTurns([turn])
    vi.advanceTimersByTime(3000)
    expect(publish).toHaveBeenLastCalledWith(first.text)
    oldOutput.onPlaybackStart({ id: 'third', text: 'Old response resumes.' })
    expect(publish.mock.calls).toEqual([[second.text], [first.text], ['Old response resumes.']])
  })

  it('tracks audio that starts in the same callback cycle as response cancellation', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    caption.updateActiveTurns([])
    output.onPlaybackStart(first)
    vi.advanceTimersByTime(3000)
    expect(publish.mock.calls).toEqual([[first.text]])
    output.onPlaybackEnd(first, { status: 'stopped' })
    vi.advanceTimersByTime(3000)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('isolates equal turn and clip IDs in separate sessions', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const otherTurn = { sessionId: 'another-session', turnId: turn.turnId }
    const oldOutput = caption.connectTurn(turn)
    const nextOutput = caption.connectTurn(otherTurn)
    caption.updateActiveTurns([turn, otherTurn])
    oldOutput.onPlaybackStart(first)
    nextOutput.onPlaybackStart({ id: first.id, text: second.text })
    caption.updateActiveTurns([otherTurn])
    oldOutput.onPlaybackEnd(first, { status: 'stopped' })
    vi.advanceTimersByTime(5000)
    expect(publish).toHaveBeenLastCalledWith(second.text)
    nextOutput.onPlaybackEnd(first, { status: 'ended' })
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(3000)
    expect(publish).toHaveBeenLastCalledWith('')
  })

  it('keeps same-response captions through audio parts that have no text', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    const empty = { id: 'empty', text: '  ' }
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    output.onPlaybackStart(empty)
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(5000)
    expect(publish.mock.calls).toEqual([[first.text]])
    output.onPlaybackEnd(empty, { status: 'ended' })
    vi.advanceTimersByTime(3000)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('does not reuse another response caption for new audio without text', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const oldOutput = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    oldOutput.onPlaybackStart(first)
    const nextOutput = caption.connectTurn(nextTurn)
    caption.updateActiveTurns([turn, nextTurn])
    nextOutput.onPlaybackStart({ id: 'empty', text: '' })
    expect(publish.mock.calls).toEqual([[first.text], ['']])
    nextOutput.onPlaybackStart(second)
    expect(publish).toHaveBeenLastCalledWith(second.text)
  })

  it('does not restart a hide timer when unrelated active turns change', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(2000)
    caption.updateActiveTurns([])
    vi.advanceTimersByTime(1000)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('waits for muted audio to stop without waiting for the model response to close', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    caption.closeTurn(turn)
    vi.advanceTimersByTime(5000)
    expect(publish.mock.calls).toEqual([[first.text]])
    expect(vi.getTimerCount()).toBe(0)

    output.onPlaybackEnd(first, { status: 'stopped', reason: 'Speech muted' })
    caption.updateActiveTurns([turn])
    vi.advanceTimersByTime(2999)
    expect(publish.mock.calls).toEqual([[first.text]])
    vi.advanceTimersByTime(1)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('starts the hide delay when mute cancels a response between audio segments', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    caption.closeTurn(turn)
    vi.advanceTimersByTime(2000)
    caption.updateActiveTurns([turn])
    caption.closeTurn(turn)
    vi.advanceTimersByTime(999)
    expect(publish.mock.calls).toEqual([[first.text]])
    vi.advanceTimersByTime(1)
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })

  it('clears pending timers and ignores late callbacks after disposal', () => {
    const publish = vi.fn()
    const caption = new PlaybackCaption(publish)
    const output = caption.connectTurn(turn)
    caption.updateActiveTurns([turn])
    output.onPlaybackStart(first)
    output.onPlaybackEnd(first, { status: 'ended' })
    caption.updateActiveTurns([])
    expect(vi.getTimerCount()).toBe(1)
    caption.dispose()
    expect(vi.getTimerCount()).toBe(0)
    expect(publish.mock.calls).toEqual([[first.text], ['']])

    output.onPlaybackStart(second)
    output.onPlaybackEnd(second, { status: 'ended' })
    caption.updateActiveTurns([turn])
    caption.connectTurn(nextTurn).onPlaybackStart(second)
    vi.runAllTimers()
    expect(publish.mock.calls).toEqual([[first.text], ['']])
  })
})
