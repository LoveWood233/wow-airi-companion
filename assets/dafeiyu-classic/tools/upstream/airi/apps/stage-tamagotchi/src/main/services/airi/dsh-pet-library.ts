import type { DshPetManifest, DshPetPack } from '../../../shared/dsh-pet'
import type { DshPetConfigure, DshPetLibraryState } from '../../../shared/dsh-pet-library'

import { randomUUID } from 'node:crypto'
import { lstat, mkdir, open, readdir, readFile, realpath, rename, rm, unlink, writeFile } from 'node:fs/promises'
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path'

import { parse } from 'valibot'

import { dshPetManifestSchema, dshPetPackSchema } from '../../../shared/dsh-pet'
import { dshPetConfigureSchema } from '../../../shared/dsh-pet-library'

const importedId = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/

/**
 * Owns local animation packs and atomic selection changes.
 * Imports copy only manifest-listed WebM files. Runtime URLs never expose arbitrary filesystem paths.
 */
export class DshPetLibrary {
  private queue = Promise.resolve()
  private selection: DshPetConfigure | undefined

  constructor(private readonly directory: string, private readonly builtin: DshPetPack) {}

  read() {
    return this.exclusive(async () => {
      await this.loadSelection()
      return this.snapshot()
    })
  }

  configure(input: DshPetConfigure) {
    const request = parse(dshPetConfigureSchema, input)
    return this.exclusive(async () => {
      await this.loadSelection()
      const state = await this.snapshot()
      if (!state.packs.some(pack => pack.id === request.selectedId))
        throw new Error('Unknown animation pack')
      await this.persistSelection(request)
      return this.snapshot()
    })
  }

  importPack(sourceDirectory: string) {
    return this.exclusive(async () => {
      await this.loadSelection()
      const source = await this.safeDirectory(sourceDirectory)
      const manifest = await this.readManifest(source)
      if (manifest.files.length > 256)
        throw new Error('Too many animation files')
      const packs = join(this.directory, 'packs')
      await mkdir(packs, { recursive: true })
      const id = randomUUID()
      const staging = join(packs, `.import-${id}`)
      const target = join(packs, id)
      await mkdir(staging)
      try {
        let totalBytes = 0
        for (const name of manifest.files) {
          const file = await this.safeFile(source, name)
          const info = await lstat(file)
          if (info.size < 4 || info.size > 32 * 1024 * 1024)
            throw new Error('Invalid animation file size')
          totalBytes += info.size
          if (totalBytes > 512 * 1024 * 1024)
            throw new Error('Animation pack exceeds the size limit')
          const handle = await open(file, 'r')
          try {
            const opened = await handle.stat()
            if (!opened.isFile() || opened.ino !== info.ino || opened.dev !== info.dev || opened.size !== info.size)
              throw new Error('Animation changed during import')
            // Read and copy the same verified handle. A path replacement cannot change the bytes copied after validation.
            const data = new Uint8Array(info.size)
            let offset = 0
            while (offset < data.length) {
              const { bytesRead } = await handle.read(data, offset, data.length - offset, offset)
              if (!bytesRead)
                throw new Error('Animation changed during import')
              offset += bytesRead
            }
            if ((await handle.stat()).size !== data.length)
              throw new Error('Animation changed during import')
            if (data[0] !== 0x1A || data[1] !== 0x45 || data[2] !== 0xDF || data[3] !== 0xA3)
              throw new Error('Invalid WebM animation')
            const destination = join(staging, name)
            await mkdir(dirname(destination), { recursive: true })
            await writeFile(destination, data, { flag: 'wx', mode: 0o600 })
          }
          finally {
            await handle.close()
          }
        }
        await this.atomicJson(join(staging, 'pack.json'), { ...manifest, id })
        await rename(staging, target)
        await this.persistSelection({ selectedId: id, scale: this.selection!.scale })
        return await this.snapshot()
      }
      finally {
        // This path is generated by this import and always stays within the private packs directory.
        if (dirname(staging) !== packs || !staging.startsWith(`${packs}${sep}.import-`))
          throw new Error('Invalid import staging path')
        await rm(staging, { recursive: true, force: true })
      }
    })
  }

  /** Resolves only a validated imported pack and one file from its manifest allowlist. */
  async resolveAsset(id: string, file: string) {
    if (!importedId.test(id))
      throw new Error('Unknown animation pack')
    const root = await this.safeDirectory(join(this.directory, 'packs', id))
    const manifest = await this.readManifest(root)
    if (manifest.id !== id || !manifest.files.includes(file))
      throw new Error('Unknown animation file')
    return this.safeFile(root, file)
  }

  private async loadSelection() {
    if (this.selection)
      return
    try {
      const file = join(this.directory, 'settings.json')
      const info = await lstat(file)
      if (!info.isFile() || info.isSymbolicLink() || info.size > 8192)
        throw new Error('Invalid animation settings')
      this.selection = parse(dshPetConfigureSchema, JSON.parse(await readFile(file, 'utf8')))
    }
    catch (error) {
      if (!error || typeof error !== 'object' || !('code' in error) || error.code !== 'ENOENT')
        throw error
      this.selection = { selectedId: this.builtin.id, scale: 1 }
    }
  }

  private async snapshot(): Promise<DshPetLibraryState> {
    const packs = [this.builtin]
    const root = join(this.directory, 'packs')
    try {
      for (const entry of await readdir(root, { withFileTypes: true })) {
        if (!entry.isDirectory() || entry.isSymbolicLink() || !importedId.test(entry.name))
          continue
        try {
          const directory = await this.safeDirectory(join(root, entry.name))
          const manifest = await this.readManifest(directory)
          if (manifest.id !== entry.name)
            continue
          for (const name of manifest.files)
            await this.safeFile(directory, name)
          packs.push(parse(dshPetPackSchema, { ...manifest, baseUrl: `dsh-pet://packs/${entry.name}` }))
        }
        catch {
          // A damaged imported pack is unavailable. The bundled pack remains selectable.
        }
      }
    }
    catch (error) {
      if (!error || typeof error !== 'object' || !('code' in error) || error.code !== 'ENOENT')
        throw error
    }
    const selection = this.selection!
    return {
      selectedId: packs.some(pack => pack.id === selection.selectedId) ? selection.selectedId : this.builtin.id,
      scale: selection.scale,
      packs,
    }
  }

  private async readManifest(directory: string): Promise<DshPetManifest> {
    const file = await this.safeFile(directory, 'pack.json')
    if ((await lstat(file)).size > 128 * 1024)
      throw new Error('Animation manifest exceeds the size limit')
    return parse(dshPetManifestSchema, JSON.parse(await readFile(file, 'utf8')))
  }

  private async safeDirectory(directory: string) {
    const absolute = resolve(directory)
    const info = await lstat(absolute)
    if (!info.isDirectory() || info.isSymbolicLink() || relative(absolute, await realpath(absolute)) !== '')
      throw new Error('Animation directories must not contain links')
    return absolute
  }

  private async safeFile(root: string, name: string) {
    if (name.includes('\\') || isAbsolute(name) || name.split('/').some(part => !part || part === '.' || part === '..'))
      throw new Error('Invalid animation path')
    const absolute = resolve(root, name)
    const rel = relative(root, absolute)
    if (isAbsolute(rel) || rel.startsWith(`..${sep}`) || rel === '..')
      throw new Error('Animation path escapes its pack')
    let cursor = root
    for (const part of name.split('/')) {
      cursor = join(cursor, part)
      const info = await lstat(cursor)
      if (info.isSymbolicLink())
        throw new Error('Animation files must not contain links')
    }
    if (!(await lstat(absolute)).isFile() || relative(absolute, await realpath(absolute)) !== '')
      throw new Error('Invalid animation file')
    return absolute
  }

  private async persistSelection(selection: DshPetConfigure) {
    await this.atomicJson(join(this.directory, 'settings.json'), selection)
    this.selection = selection
  }

  private async atomicJson(file: string, data: object) {
    await mkdir(dirname(file), { recursive: true })
    const temporary = `${file}.${randomUUID()}.tmp`
    try {
      const handle = await open(temporary, 'wx', 0o600)
      try {
        await handle.writeFile(JSON.stringify(data), 'utf8')
        await handle.sync()
      }
      finally {
        await handle.close()
      }
      await rename(temporary, file)
    }
    finally {
      await unlink(temporary).catch(() => {})
    }
  }

  private exclusive<T>(operation: () => Promise<T>) {
    const result = this.queue.then(operation)
    this.queue = result.then(() => {}, () => {})
    return result
  }
}
